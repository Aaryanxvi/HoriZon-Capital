const { Tray, Menu, app, nativeImage } = require("electron");
const path = require("path");

let tray = null;

/** Tray icon: closing the window hides it, so this is the way back in. */
function createTray(mainWindow) {
  let icon;
  try {
    icon = nativeImage.createFromPath(path.join(__dirname, "icons", "icon.ico"));
    if (icon.isEmpty()) icon = nativeImage.createEmpty();
  } catch {
    icon = nativeImage.createEmpty();
  }

  tray = new Tray(icon);
  tray.setToolTip("Horizon Capital — engine running");

  const show = () => {
    if (mainWindow.isMinimized()) mainWindow.restore();
    mainWindow.show();
    mainWindow.focus();
  };

  tray.setContextMenu(
    Menu.buildFromTemplate([
      { label: "Open Horizon Capital", click: show },
      { label: "Hide window", click: () => mainWindow.hide() },
      { type: "separator" },
      {
        label: "Quit (stops the agents)",
        click: () => {
          app.isQuitting = true;
          app.quit();
        },
      },
    ]),
  );

  tray.on("click", () => (mainWindow.isVisible() ? mainWindow.hide() : show()));

  return tray;
}

module.exports = { createTray };
